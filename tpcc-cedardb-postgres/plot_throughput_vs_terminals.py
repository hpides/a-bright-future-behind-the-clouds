#!/usr/bin/env python3
"""
plot_throughput_vs_terminals.py

Parse one or more BenchBase `samples.csv` files -- each one tagged with a
machine and a database -- and plot average throughput as a function of the
number of terminals. Color encodes the machine, marker shape encodes the
database, so you can compare both dimensions in a single chart.

Each samples.csv contains a time-series of throughput samples across the
*whole* run (all phases back to back). To get a single throughput value per
terminal count, this script slices each file by known phase time windows
(derived from the <warmup> and <time> values in your BenchBase config) and
averages the throughput within each window.

USAGE
-----
    python plot_throughput_vs_terminals.py \\
        machineA_pg_samples.csv machineA_mysql_samples.csv \\
        machineB_pg_samples.csv machineB_mysql_samples.csv \\
        --phases "1:10:60,32:10:60" \\
        --machines "A" "A" "B" "B" \\
        --databases "Postgres" "MySQL" "Postgres" "MySQL" \\
        --output throughput_vs_terminals.png

--files, --machines, and --databases are positional/parallel lists: the i-th
file belongs to the i-th machine and the i-th database.

--phases describes the sequence of work phases in your BenchBase config, in
the SAME order they appear in <works>, as comma-separated
`terminals:warmup:time` triples (seconds). E.g. for a config with:

    <works>
        <work><active_terminals>1</active_terminals><warmup>10</warmup><time>60</time>...</work>
        <work><active_terminals>32</active_terminals><warmup>10</warmup><time>60</time>...</work>
    </works>

pass --phases "1:10:60,32:10:60"

If a phase has no <warmup>, you can omit it: "1:60,32:60" (warmup defaults to 0).

All samples.csv files must have been generated by runs that used the exact
same --phases sequence (same warmup/time durations), since the script assumes
that phase N occupies the same absolute time window in every file.
"""

import argparse
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

# Column name candidates, to tolerate small naming differences across
# BenchBase versions/DBMS profiles. Add more here if your file uses a
# different header.
TIME_COL_CANDIDATES = ["Time (seconds)", "time", "Time", "elapsed_sec", "second"]
THROUGHPUT_COL_CANDIDATES = [
    "Throughput (requests/second)",
    "throughput",
    "Throughput",
    "tps",
]

# Distinct marker shapes cycled across databases (extend if you have more
# than 8 databases).
MARKER_CYCLE = ["o", "s", "^", "D", "v", "P", "X", "*"]

# Matplotlib's default color cycle, cycled across machines (extend/replace if
# you have more than 10 machines).
COLOR_CYCLE = plt.rcParams["axes.prop_cycle"].by_key()["color"]


def parse_phases(spec: str):
    """Parse '--phases' string into a list of {"terminals","warmup","time"} dicts."""
    phases = []
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        parts = chunk.split(":")
        if len(parts) == 3:
            terminals, warmup, time = parts
        elif len(parts) == 2:
            terminals, time = parts
            warmup = "0"
        else:
            raise ValueError(
                f"Invalid phase spec '{chunk}'. Expected 'terminals:warmup:time' "
                f"or 'terminals:time'."
            )
        phases.append(
            {"terminals": int(terminals), "warmup": float(warmup), "time": float(time)}
        )
    if not phases:
        raise ValueError("No phases parsed from --phases")
    return phases


def compute_phase_windows(phases):
    """Turn per-phase (warmup, time) durations into cumulative [start, end) windows."""
    windows = []
    cursor = 0.0
    for p in phases:
        start = cursor + p["warmup"]
        end = start + p["time"]
        windows.append({"terminals": p["terminals"], "start": start, "end": end})
        cursor = end
    return windows


def find_column(df, candidates, kind):
    for c in candidates:
        if c in df.columns:
            return c
    raise ValueError(
        f"Could not find a {kind} column in columns {list(df.columns)}. "
        f"Tried: {candidates}. Add your header to the *_CANDIDATES list."
    )


def load_samples(csv_path):
    df = pd.read_csv(csv_path)
    time_col = find_column(df, TIME_COL_CANDIDATES, "time")
    throughput_col = find_column(df, THROUGHPUT_COL_CANDIDATES, "throughput")
    return df, time_col, throughput_col


def average_throughput_per_phase(df, time_col, throughput_col, windows):
    """Return list of (terminals, mean_throughput) for each phase window."""
    results = []
    for w in windows:
        mask = (df[time_col] >= w["start"]) & (df[time_col] < w["end"])
        subset = df.loc[mask, throughput_col]
        avg = subset.mean() if not subset.empty else float("nan")
        n = int(subset.shape[0])
        results.append(
            {"terminals": w["terminals"], "throughput": avg, "n_samples": n}
        )
    return results


def parse_args():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("files", nargs="+", help="samples.csv files, one per (machine, database) run")
    parser.add_argument(
        "--phases",
        required=True,
        help="Phase spec: 'terminals:warmup:time,...' matching your BenchBase <works> order",
    )
    parser.add_argument(
        "--machines",
        nargs="+",
        required=True,
        help="Machine name for each file, in order (parallel to 'files')",
    )
    parser.add_argument(
        "--databases",
        nargs="+",
        required=True,
        help="Database name for each file, in order (parallel to 'files')",
    )
    parser.add_argument(
        "--output", default="throughput_vs_terminals.png", help="Output image path"
    )
    parser.add_argument(
        "--csv-out",
        default=None,
        help="Optional: also write the per-phase averages to this CSV path",
    )
    args = parser.parse_args()

    n = len(args.files)
    if len(args.machines) != n or len(args.databases) != n:
        sys.exit(
            f"Got {n} files, {len(args.machines)} --machines, and "
            f"{len(args.databases)} --databases. All three must have the same "
            f"length and be given in matching order."
        )
    return args


def main():
    args = parse_args()
    phases = parse_phases(args.phases)
    windows = compute_phase_windows(phases)

    # Stable color-per-machine and marker-per-database assignment, based on
    # first-seen order.
    machine_order = list(dict.fromkeys(args.machines))
    database_order = list(dict.fromkeys(args.databases))
    machine_color = {
        m: COLOR_CYCLE[i % len(COLOR_CYCLE)] for i, m in enumerate(machine_order)
    }
    database_marker = {
        d: MARKER_CYCLE[i % len(MARKER_CYCLE)] for i, d in enumerate(database_order)
    }

    all_rows = []  # for optional CSV export
    fig, ax = plt.subplots(figsize=(8, 5))

    for f, machine, database in zip(args.files, args.machines, args.databases):
        df, time_col, throughput_col = load_samples(f)
        phase_results = average_throughput_per_phase(df, time_col, throughput_col, windows)

        for r in phase_results:
            if r["n_samples"] == 0:
                print(
                    f"warning: no samples found for machine={machine} "
                    f"database={database} at terminals={r['terminals']} "
                    f"(check --phases matches this run's config)",
                    file=sys.stderr,
                )
            all_rows.append({"machine": machine, "database": database, **r})

        terminals = [r["terminals"] for r in phase_results]
        throughput = [r["throughput"] for r in phase_results]
        ax.plot(
            terminals,
            throughput,
            color=machine_color[machine],
            marker=database_marker[database],
            markersize=8,
            linewidth=2,
            label=f"{machine} / {database}",
        )

    ax.set_xlabel("Number of terminals")
    ax.set_ylabel("Throughput (requests/second)")
    ax.set_title("Throughput vs. Terminals")
    ax.grid(True, alpha=0.3)

    # Two separate legends: one mapping color -> machine, one mapping
    # marker shape -> database. This keeps the two dimensions visually
    # distinguishable instead of one long combined legend.
    machine_handles = [
        plt.Line2D([0], [0], color=machine_color[m], linewidth=2, label=m)
        for m in machine_order
    ]
    database_handles = [
        plt.Line2D(
            [0], [0], color="black", marker=database_marker[d],
            linestyle="None", markersize=8, label=d,
        )
        for d in database_order
    ]
    legend1 = ax.legend(handles=machine_handles, title="Machine", loc="upper left")
    ax.add_artist(legend1)
    ax.legend(handles=database_handles, title="Database", loc="lower right")

    fig.tight_layout()
    fig.savefig(args.output, dpi=150)
    print(f"Saved plot to {args.output}")

    if args.csv_out:
        pd.DataFrame(all_rows).to_csv(args.csv_out, index=False)
        print(f"Saved per-phase averages to {args.csv_out}")


if __name__ == "__main__":
    main()
